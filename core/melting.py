from dataclasses import dataclass, field
from typing import List


def calc_metal_charge(
    annual_output_t: float,
    brak_pct: float = 5.0,
    litniki_pribyli_pct: float = 28.9,
    ugar_pct: float = 5.0,
) -> float:
    """Рассчитать годовую металлозавалку по балансу металла (диплом, табл. 6).

    Структура баланса (как в «Пример диплома.pdf», табл. 6):
        Жидкий металл      = М_зав × (1 − У/100)          (угар 5%)
        Годное литьё       = Жидкий − Литники/прибыли − Брак
        Годное литьё       = М_зав × [ (1−У/100) − ЛП/100 − Бр/100 ]
    Отсюда:
        М_зав = М_выпуска / (1 − У/100 − ЛП/100 − Бр/100)

    Эталон диплома: 37 000 т годного выпуска → ровно 58 932 т завалки при
    Бр=5%, ЛП=28.9%, У=5% (суммарные потери 38.9%, выход годного 61.1%).

    ВАЖНО: проценты брака, литников и угара в проекте задаются ОТНOSITELYNO
    годного литья (в дипломе — от металлозавалки). Поэтому сначала
    вычисляется эталонная доля отходов (w×(1+w)/(1−w+2w²)), и она же
    используется как база пересчёта процентов проекта. При w=0.289 доля
    равна 0.339 — ровно как в балансе диплома (18986/58932 = 32.2% + ...).

    Args:
        annual_output_t: годовой выпуск годных отливок, т
        brak_pct: процент брака от годного литья, %
        litniki_pribyli_pct: процент литников и прибылей от годного литья, %
        ugar_pct: процент угара от годного литья, %

    Returns:
        Годовая металлозавалка, т
    """
    # Доля литейных отходов в металлозавалке по эталонной модели диплома
    w = litniki_pribyli_pct / 100.0
    share = w * (1.0 + w) / (1.0 - w + 2.0 * w * w) if w > 0 else 0.0
    # Проценты проекта (от годного) приводим к той же базе — доле от завалки
    scale = share / w if w > 0 else 1.0
    lp_share = share                                   # литники и прибыли
    brak_share = (brak_pct / 100.0) * scale            # брак
    ugar_share = (ugar_pct / 100.0) * scale            # угар
    k_out = 1.0 - (lp_share + brak_share + ugar_share)
    if k_out <= 0:
        raise ValueError(
            f"Суммарные потери превышают 100% — некорректные исходные данные "
            f"(ЛП={litniki_pribyli_pct}%, Бр={brak_pct}%, У={ugar_pct}%)"
        )
    return annual_output_t / k_out


@dataclass
class MeltingCalculation:
    """Расчет плавильного отделения"""
    annual_metal_charge_t: float  # Годовая металлозавалка, т
    furnace_type: str  # Тип печи (ИСТ-6М1, ДСП, и т.д.)
    furnace_capacity_t: float  # Емкость тигля, т
    furnace_productivity_t_h: float  # Производительность, т/ч
    fund_hours: float  # Действительный фонд времени, ч
    k_uneven: float  # Коэффициент неравномерности (1.0-1.2)
    
    # Результаты расчета
    furnace_count: int  # Количество печей
    load_factor: float  # Коэффициент загрузки